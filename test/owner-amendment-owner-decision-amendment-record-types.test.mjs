import test from 'node:test';
import assert from 'node:assert/strict';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fixtureRoot = join(root, 'test/fixtures/owner-amendment-owner-decision-amendment-record-contract');
const configPath = join(root, 'tsconfig.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
assert.equal(config.error, undefined);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root, undefined, configPath);
assert.deepEqual(parsed.errors, []);
const options = { ...parsed.options, rootDir: root, noEmit: true };

function summarize(diagnostics) {
  return diagnostics.map(item => ({
    file: item.file?.fileName,
    line: item.file && item.start !== undefined ? item.file.getLineAndCharacterOfPosition(item.start).line + 1 : 0,
    code: item.code,
    message: ts.flattenDiagnosticMessageText(item.messageText, '\n'),
  }));
}

function compile(name) {
  const file = join(fixtureRoot, name);
  const program = ts.createProgram([file], options);
  const diagnostics = summarize(ts.getPreEmitDiagnostics(program));
  assert.deepEqual(diagnostics.filter(item => item.file !== file), [], 'AmendmentRecord implementation contract must remain error-free');
  return diagnostics.filter(item => item.file === file);
}

test('AmendmentRecord producer types reflect canonical records, generated bytes, and unnormalized coercion fields', () => {
  assert.deepEqual(compile('positive.mts'), []);
});

test('AmendmentRecord contracts reject mutation, narrowing unknown values, and success fields on incomplete results', () => {
  const diagnostics = compile('negative.mts');
  assert.deepEqual(diagnostics.map(item => [item.code, item.line]), [
    [2540, 10], [2322, 11], [2322, 13], [2322, 19], [2339, 22],
  ]);
  assert.match(diagnostics[1].message, /unknown.*string|not assignable/i);
  assert.match(diagnostics[2].message, /unknown.*string|not assignable/i);
  assert.match(diagnostics[3].message, /undefined.*string|not assignable to type 'string'/i);
  assert.match(diagnostics[4].message, /repository.*does not exist|Property .*repository/i);
});
